def calculate_average(seeds_data):
    """Tính trung bình từ dữ liệu của nhiều seeds"""
    num_tasks = len(seeds_data[0]['ap'])
    num_seeds = len(seeds_data)

    averaged_ap = []
    averaged_af = []

    for task_idx in range(num_tasks):
        # Tính trung bình AP cho task hiện tại
        ap_sum = sum(seed['ap'][task_idx] for seed in seeds_data)
        averaged_ap.append(round(ap_sum / num_seeds, 3))

        # Tính trung bình AF cho task hiện tại
        af_sum = sum(seed['af'][task_idx] for seed in seeds_data)
        averaged_af.append(round(af_sum / num_seeds, 3))

    return averaged_ap, averaged_af

def calculate_std(seeds_data):
    """Tính độ lệch chuẩn từ dữ liệu của nhiều seeds"""
    num_tasks = len(seeds_data[0]['ap'])
    num_seeds = len(seeds_data)

    std_ap = []
    std_af = []

    for task_idx in range(num_tasks):
        # Tính trung bình AP cho task hiện tại
        ap_values = [seed['ap'][task_idx] for seed in seeds_data]
        mean_ap = sum(ap_values) / num_seeds
        variance_ap = sum((x - mean_ap) ** 2 for x in ap_values) / num_seeds
        std_ap.append(round(variance_ap ** 0.5, 3))

        # Tính trung bình AF cho task hiện tại
        af_values = [seed['af'][task_idx] for seed in seeds_data]
        mean_af = sum(af_values) / num_seeds
        variance_af = sum((x - mean_af) ** 2 for x in af_values) / num_seeds
        std_af.append(round(variance_af ** 0.5, 3))

    return std_ap, std_af

